"""Knowledge-base ingestion: python -m src.rag.ingest  (or: python run.py ingest)

1. Upserts every data/kb/**/*.md|.txt file into kb_documents (keyed by path).
2. (Re)chunks every document whose content changed since it was last chunked,
   including documents edited directly in the Supabase dashboard.
3. Embeds the chunks if config/app.yaml retrieval.embedding_provider is set.

Full-text search columns are generated by Postgres, so chunks are searchable
as soon as they are written.
"""
from __future__ import annotations

import argparse
import hashlib

from src.config import ROOT, app_config
from src.rag.embeddings import embed
from src.tools.store import get_store

KB_DIR = ROOT / "data" / "kb"


def chunk_text(text: str, size: int, overlap: int) -> list[str]:
    """Split on paragraph boundaries, packing paragraphs up to `size` chars."""
    paragraphs = [p.strip() for p in text.split("\n\n") if p.strip()]
    chunks, current = [], ""
    for p in paragraphs:
        if len(p) > size and current:             # flush before splitting a huge paragraph
            chunks.append(current)
            current = ""
        while len(p) > size:
            chunks.append(p[:size])
            p = p[size - overlap:]
        if current and len(current) + len(p) + 2 > size:
            chunks.append(current)
            current = current[-overlap:] + "\n\n" + p if overlap else p
        else:
            current = f"{current}\n\n{p}" if current else p
    if current:
        chunks.append(current)
    return chunks


def _title(text: str, fallback: str) -> str:
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return fallback


def load_files(store) -> int:
    n = 0
    for path in sorted(KB_DIR.rglob("*")):
        if path.suffix.lower() not in (".md", ".txt") or path.name.lower() == "readme.md":
            continue
        text = path.read_text(encoding="utf-8")
        source = path.relative_to(ROOT).as_posix()
        store.upsert_document({
            "source": source,
            "title": _title(text, path.stem.replace("_", " ")),
            "content": text,
            "content_hash": hashlib.sha256(text.encode()).hexdigest(),
        })
        n += 1
    return n


def chunk_stale(store) -> int:
    cfg = app_config()["retrieval"]
    n = 0
    for doc in store.documents_needing_chunks():
        pieces = chunk_text(doc["content"], cfg["chunk_chars"], cfg["chunk_overlap"])
        vectors = embed(pieces) or [None] * len(pieces)
        store.replace_chunks(doc["id"], [
            {"document_id": doc["id"], "chunk_index": i, "content": c, "embedding": v}
            for i, (c, v) in enumerate(zip(pieces, vectors))
        ])
        n += 1
    return n


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--skip-files", action="store_true", help="only re-chunk documents edited in Supabase")
    args = ap.parse_args(argv)
    store = get_store()
    loaded = 0 if args.skip_files else load_files(store)
    chunked = chunk_stale(store)
    print(f"loaded {loaded} file(s) from data/kb, chunked {chunked} document(s)")


if __name__ == "__main__":
    main()
