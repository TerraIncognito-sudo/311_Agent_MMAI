"""Knowledge-base sync: python -m src.rag.ingest  (or: python run.py ingest)

Supabase `kb_documents` is the only source of knowledge-base content. Add,
edit or deactivate documents in the Supabase dashboard; the running server
picks the change up on its own (start_sync), with no redeploy.

1. (Re)chunks every active document whose content changed since it was last
   chunked, and every new one (the `kb_documents_stale` view).
2. Embeds the chunks if app.yaml retrieval.embedding_provider is set.
3. Optional bulk upload: `--import DIR` upserts every DIR/**/*.md|.txt file
   into kb_documents first (keyed by path relative to DIR).

Full-text search columns are generated by Postgres, so chunks are searchable
as soon as they are written. Deactivated documents (active = false) drop out
of retrieval immediately; deleted ones take their chunks with them.
"""
from __future__ import annotations

import argparse
import hashlib
import threading
from pathlib import Path

from src.config import app_config, refresh
from src.rag.embeddings import embed
from src.tools.store import get_store


def chunk_text(text: str, size: int, overlap: int) -> list[str]:
    """Split on paragraph boundaries, packing paragraphs up to `size` chars."""
    paragraphs = [p.strip() for p in text.split("\n\n") if p.strip()]
    chunks, current = [], ""
    for p in paragraphs:
        if len(p) > size and current:             # flush before splitting a huge paragraph
            chunks.append(current)
            current = ""
        while len(p) > size:
            chunks.append(p[:size])
            p = p[size - overlap:]
        if current and len(current) + len(p) + 2 > size:
            chunks.append(current)
            current = current[-overlap:] + "\n\n" + p if overlap else p
        else:
            current = f"{current}\n\n{p}" if current else p
    if current:
        chunks.append(current)
    return chunks


def _title(text: str, fallback: str) -> str:
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return fallback


def import_files(store, directory: Path) -> int:
    """Bulk upload a folder of .md/.txt files into kb_documents."""
    n = 0
    for path in sorted(directory.rglob("*")):
        if path.suffix.lower() not in (".md", ".txt") or path.name.lower() == "readme.md":
            continue
        text = path.read_text(encoding="utf-8")
        store.upsert_document({
            "source": path.relative_to(directory).as_posix(),
            "title": _title(text, path.stem.replace("_", " ")),
            "content": text,
            "content_hash": hashlib.sha256(text.encode()).hexdigest(),
        })
        n += 1
    return n


_chunk_lock = threading.Lock()   # the sync thread and /admin saves both chunk


def chunk_stale(store) -> int:
    with _chunk_lock:
        return _chunk_stale(store)


def _chunk_stale(store) -> int:
    cfg = app_config()["retrieval"]
    n = 0
    for doc in store.documents_needing_chunks():
        pieces = chunk_text(doc["content"], cfg["chunk_chars"], cfg["chunk_overlap"])
        vectors = embed(pieces) or [None] * len(pieces)
        store.replace_chunks(doc["id"], [
            {"document_id": doc["id"], "chunk_index": i, "content": c, "embedding": v}
            for i, (c, v) in enumerate(zip(pieces, vectors))
        ])
        n += 1
    return n


def start_sync(interval_s: float, store=None) -> threading.Event | None:
    """Every `interval_s` seconds, in a background thread: re-chunk KB edits
    and pick up config edits made in the Supabase dashboard. Returns an
    Event that stops the loop, or None if disabled."""
    if interval_s <= 0:
        return None
    stop = threading.Event()

    def loop():
        while True:
            try:
                n = chunk_stale(store or get_store())
                if n:
                    print(f"[sync] re-chunked {n} document(s)")
                if refresh():
                    print("[sync] applied config edits from Supabase")
            except Exception as e:   # Supabase or the embedding model is down; try again next round
                print(f"[sync] failed: {type(e).__name__}: {e}")
            if stop.wait(interval_s):
                return

    threading.Thread(target=loop, name="kb-sync", daemon=True).start()
    return stop


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--import", dest="import_dir", type=Path, metavar="DIR",
                    help="first upload every .md/.txt file in DIR to kb_documents")
    args = ap.parse_args(argv)
    store = get_store()
    loaded = import_files(store, args.import_dir) if args.import_dir else 0
    chunked = chunk_stale(store)
    print(f"imported {loaded} file(s), chunked {chunked} document(s)")


if __name__ == "__main__":
    main()
